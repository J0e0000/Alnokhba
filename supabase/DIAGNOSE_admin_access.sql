-- شغّل السطر ده الأول في SQL Editor، وحط إيميلك:

select id, email, is_admin, subscription_status
from profiles
where email = 'ضع إيميلك هنا';

-- لو عمود is_admin ظهر false أو فاضي، ده سبب كل المشكلة — كل أزرار الأدمن
-- (تمديد اشتراك، تفعيل ألعاب، إلغاء اشتراك) بترفضها قاعدة البيانات بصمت
-- من غير ما تظهرلك رسالة خطأ واضحة (المشكلة دي اتصلحت في كود الواجهة، هتظهرلك
-- رسالة خطأ واضحة من دلوقتي، لكن الحل الحقيقي هو تفعيل الصلاحية دي أصلاً).

-- ============================================================================
-- الحل: فعّل صلاحية الأدمن (استبدل الإيميل بإيميلك، وشغّل السطر ده لوحده)
-- ============================================================================
update profiles set is_admin = true where email = 'ضع إيميلك هنا';

